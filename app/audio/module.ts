/**
 * `react-native-audio-api` 를 **늦게** 부른다.
 *
 * 왜 파일 맨 위에서 값으로 import 하지 않았나
 * -------------------------------------------
 * 이 라이브러리는 import 되는 순간 네이티브 모듈을 설치하고, 못 찾으면 그 자리에서 던진다
 * (`AudioAPIModule` 의 생성자가 그렇게 되어 있다). 값으로 import 하면 그 예외가 **번들
 * 평가 중에** 터지므로 **앱 전체가 뜨지 않는다** — 연결 확인 화면까지 함께 죽는다는 뜻이다.
 * JS 만 새로고침하고 APK 를 다시 빌드하지 않았을 때 실제로 그렇게 된다.
 *
 * 그래서 타입만 위에서 가져오고(타입은 컴파일 뒤 사라진다) 실물은 마이크를 열거나 소리를
 * 낼 때 여기서 부른다. 실패하면 실시간 화면의 오류 상자에 이유가 뜨고, 연결 확인 화면은
 * 그대로 산다 — "지금 되는 것을 잃지 않는다"가 이 한 겹의 목적이다.
 *
 * `import()` 가 아니라 `require` 인 이유
 * -------------------------------------
 * 동적 `import()` 는 jest 에서 `--experimental-vm-modules` 없이는 돌지 않는다(실측).
 * `require` 는 Metro 도 jest 도 그대로 이해하고, 어차피 같은 번들 안에 있는 모듈이라
 * 비동기로 가져올 이유도 없다.
 */

/** 실물 모듈. 네이티브가 없으면 여기서 던진다. */
export function audioApi(): typeof import('react-native-audio-api') {
  return require('react-native-audio-api');
}
